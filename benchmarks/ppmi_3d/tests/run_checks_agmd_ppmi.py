@check("9. Student is MRI-only (DaT NaN / missing file -> same prediction) and batch-independent (CPU, float64)")
def mri_only_test():
    m = AGMDMethod(PROTOCOL, CONFIG)
    assert m.needs_dat("student", "eval") is False
    seed_everything(0)
    s, _ = quiet(m.build, "student")
    s = s.to(DEVICE).eval()
    b = real_batch(TRAIN0, 2, load_dat=True)
    with torch.no_grad():
        p_ref = m.predict("student", s, b)
        b_nan = dict(b, dat=torch.full_like(b["dat"], float("nan")))
        p_nan = m.predict("student", s, b_nan)
    missing = [r.__class__(**{**r.__dict__, "dat_path": Path("Z:/does/not/exist.nii.gz")}) for r in TRAIN0[:2]]
    loader = make_loader(missing, PROTOCOL, m.needs_dat("student", "eval"), shuffle=False, seed=0)
    bm = to_device(next(iter(loader)), DEVICE)
    with torch.no_grad():
        p_missing = m.predict("student", s, bm)
    assert torch.equal(p_ref, p_nan) and torch.equal(p_ref, p_missing), (p_ref, p_nan, p_missing)
    sc = copy.deepcopy(s).double().cpu().eval()
    x = real_batch(TRAIN0, 3, load_dat=False, device=torch.device("cpu"))["mri"].double()
    with torch.no_grad():
        full, alone = sc(x)["pred"], sc(x[:1])["pred"]
        other_peers = sc(x[[0, 2, 0]])["pred"]
    torch.testing.assert_close(full[0], other_peers[0], rtol=0, atol=1e-10)
    d = float((full[0] - alone[0]).abs())
    # Changing matrix batch size can perturb float32 cosine kNN near a tie.
    # Keep a strict peer-change check and check numerical parity across sizes separately.
    assert d < 1e-5, d
    log(f"    pred unchanged with DaT=NaN and with a missing DaT file; |pred(batch of 3) - pred(alone)| = {d:.1e} "
        f"(CPU float64 model, float32 cosine kNN); replacing batch peers passed atol=1e-10")
    return "OK"


