@check("14. Graph tokens and adjacency are subject-local for batch 8 and a singleton tail")
def case_graph_test():
    seed_everything(0)
    graph, _ = quiet(BrainGraph, PROTOCOL, CONFIG, (64, 128, 256, 512))
    graph = graph.double().eval()
    sizes = dict(zip(graph.layout.layers, graph.layout.stage_sizes))
    with torch.no_grad():
        for batch_size in (8, 1):
            feats = {layer: torch.randn(batch_size, channels, *sizes[layer], dtype=torch.float64)
                     for layer, channels in ((1, 128), (2, 256))}
            tokens, adj = graph(feats)
            assert tokens.shape == (batch_size, 332, 64) and torch.isfinite(tokens).all()
            for i in range(batch_size):
                single, single_adj = graph({layer: x[i:i + 1] for layer, x in feats.items()})
                torch.testing.assert_close(tokens[i:i + 1], single, rtol=1e-10, atol=1e-10)
                assert all(torch.equal(a[i:i + 1], b) for a, b in zip(adj, single_adj))
    return "All nine synthetic cases matched their single-subject tokens and edges"


