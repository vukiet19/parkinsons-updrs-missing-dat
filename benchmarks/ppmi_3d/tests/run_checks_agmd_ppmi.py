GROUPS = ("mri_encoder.stem", "mri_encoder.stages.0", "mri_encoder.stages.1", "mri_encoder.stages.2",
          "mri_encoder.stages.3", "graph.gcn", "readout.encoder", "readout.down", "head")


def reached(model, loss):
    params = [(n, p) for n, p in model.named_parameters() if p.requires_grad]
    grads = torch.autograd.grad(loss, [p for _, p in params], retain_graph=True, allow_unused=True)
    hit = set()
    for (n, _), g in zip(params, grads):
        if g is not None and g.abs().sum() > 0:
            hit.update(gr for gr in GROUPS if n.startswith(gr))
    return hit


@check("6. Gradients: teacher stage reaches every used teacher parameter; student stage: frozen teacher "
       "(grad None, state_dict incl. BN buffers unchanged after a step); each distillation term -> expected groups")
def gradient_test():
    seed_everything(0)
    m = AGMDMethod(PROTOCOL, CONFIG)
    (t, s), _ = quiet(lambda: (m.build("teacher").to(DEVICE), m.build("student").to(DEVICE)))
    b = real_batch(TRAIN0, 2)
    loss, _ = m.training_step("teacher", t, {}, b)
    loss.backward()
    no_grad = sorted({".".join(n.split(".")[:3]) for n, p in t.named_parameters() if p.grad is None})
    # D-032/D-036: CMT and graph use stages [1, 2]; encoder stage 3 is computed but unused -> no gradient.
    assert no_grad == ["dat_encoder.stages.3", "mri_encoder.stages.3"], no_grad
    log(f"    teacher params without grad: {no_grad} (stage 3 unused by design: cmt/graph layers = [1, 2])")
    t.zero_grad(set_to_none=True)
    freeze(t)
    before = {k: v.detach().clone() for k, v in t.state_dict().items()}
    opt = torch.optim.Adam(s.parameters(), lr=1e-4)
    loss, _ = m.training_step("student", s, {"teacher": t}, b)
    opt.zero_grad()
    loss.backward()
    opt.step()
    assert all(p.grad is None for p in t.parameters())
    assert all(torch.equal(v, before[k]) for k, v in t.state_dict().items())
    s_no_grad = sorted({".".join(n.split(".")[:3]) for n, p in s.named_parameters() if p.grad is None})
    assert s_no_grad == ["mri_encoder.stages.3"], s_no_grad
    out = s(b["mri"])
    with torch.no_grad():
        ot = t(b["mri"], b["dat"])
    terms = m.distill_terms(out, ot)
    enc1 = {"mri_encoder.stem", "mri_encoder.stages.0", "mri_encoder.stages.1"}
    enc2 = enc1 | {"mri_encoder.stages.2"}
    expect = {"shallow_1": enc1, "shallow_2": enc2, "graph": enc2 | {"graph.gcn"},
              "global": enc2 | {"graph.gcn", "readout.encoder", "readout.down"},
              "logit": enc2 | {"graph.gcn", "readout.encoder", "readout.down", "head"}}
    for name, groups in expect.items():
        got = reached(s, terms[name].mean())
        assert got == groups, (name, sorted(got ^ groups))
        log(f"    {name:9s} -> {sorted(got)}")
    return "OK"


@check("7. Overfit: 8 subjects (1 sample each), <= 200 epochs, task loss of teacher and student < 10% of start")
def overfit_test():
    rows = [r for r in TRAIN0 if r.dat_path is not None][:8]
    assert len({r.subject_id for r in rows}) == 8
    proto = apply_overrides(PROTOCOL, ["training.batch_size=8"])
    scaler = TargetScaler.fit(rows)
    report, teacher = [], None
    for stage in ("teacher", "student"):
        seed_everything(0, bool(proto["training"]["deterministic"]))
        m = AGMDMethod(proto, CONFIG)
        model, _ = quiet(m.build, stage)
        model = model.to(DEVICE)
        frozen = {"teacher": freeze(teacher)} if stage == "student" else {}
        opt = torch.optim.Adam(model.parameters(), lr=float(proto["training"]["lr"]))
        loader = make_loader(rows, proto, m.needs_dat(stage, "train"), shuffle=True, seed=0)
        curve, first, done = [], None, None
        for epoch in range(1, 201):
            model.train()
            for batch in loader:
                batch = to_device(batch, DEVICE)
                batch["y_z"] = scaler.normalize(batch["y"])
                loss, terms = m.training_step(stage, model, frozen, batch)
                opt.zero_grad()
                loss.backward()
                opt.step()
            task = float(terms["task"])
            first = task if first is None else first
            if epoch % 10 == 0 or epoch == 1:
                curve.append(f"{epoch}:{task:.4f}")
            if done is None and task < 0.1 * first:
                done = epoch
        report.append(f"{stage}: task {first:.4f} -> {task:.5f}; < 10% first at epoch {done}; curve {' '.join(curve)}")
        log("    " + report[-1])
        assert task < 0.1 * first, report[-1]
        if stage == "teacher":
            teacher = model
    return "both below 10%"


