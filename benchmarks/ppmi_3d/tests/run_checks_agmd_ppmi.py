@check("2. atlas_area layout at stages [1, 2]: 166 nodes, k 13, 10/10 key ROIs, 38 anatomical edges (= P1a); "
       "coverage sums to 1 per cell; key-ROI coverage = P1a")
def layout_test():
    lay, out = quiet(GraphLayout, PROTOCOL, CONFIG)
    info = lay.node_info()
    p1a_opts = [r for r in csv.DictReader((P1A / "options_summary.csv").open(encoding="utf-8"))
                if r["option"] == "a+c" and r["background"] == "True"]
    atlas = load_atlas(ATLAS)
    p1a = p1a_module()
    atlas_np = atlas.numpy().astype(np.int16)
    for i, li in enumerate(info["layers"]):
        ref = next(r for r in p1a_opts if int(r["stage"]) == li["stage"])
        assert (li["n_nodes"], li["k"], li["n_key_present"], li["anat_edges"]) == \
               (int(ref["n_nodes"]), int(ref["k"]), int(ref["key_rois_as_nodes"]), int(ref["anat_edges_grid_adjacency"])), (li, ref)
        assert (li["n_nodes"], li["k"], li["n_key_present"], li["anat_edges"]) == (166, 13, 10, 38)
        cov = area_coverage(atlas, li["size"], lay.node_ids[i])
        err_sum = float((cov.flatten(1).sum(0) - 1).abs().max())
        assert err_sum <= 1e-6, err_sum
        cov_np, _, _ = p1a.coverage(atlas_np, li["size"])               # independent numpy version (P1a)
        err_p1a = max(abs(li["key_sum_coverage"][str(k)] - float(cov_np[k].sum())) for k in KEY_IDS)
        csv_rows = {int(r["id"]): float(r["area_sum_coverage"]) for r in
                    csv.DictReader((P1A / f"key_roi_coverage_stage{li['stage']}.csv").open(encoding="utf-8"))}
        err_csv = max(abs(li["key_sum_coverage"][str(k)] - csv_rows[k]) for k in KEY_IDS)
        assert err_p1a <= 1e-6 and err_csv <= 5e-4, (err_p1a, err_csv)
        log(f"    stage {li['stage']} {li['size']}: nodes {li['n_nodes']} k {li['k']} key {li['n_key_present']}/10 "
            f"edges {li['anat_edges']}; max |sum_n coverage - 1| = {err_sum:.1e}; key sum-coverage vs P1a numpy "
            f"{err_p1a:.1e}, vs P1a CSV (3 decimals) {err_csv:.1e}")
        log(f"      key sum-coverage: {li['key_sum_coverage']}")
    assert "[agmd graph]" in out and "atlas_area" in out
    return "matches P1a"


@check("3. Node features = coverage-weighted mean (explicit loop) on random feature maps")
def node_feature_test():
    lay, _ = quiet(GraphLayout, PROTOCOL, CONFIG)
    atlas = load_atlas(ATLAS)
    errs = []
    for i, size in enumerate(lay.stage_sizes):
        f = torch.randn(2, 4, *size, dtype=torch.float32)
        got = lay.node_features(i, f)
        cov = area_coverage(atlas, size, lay.node_ids[i])
        ref = torch.zeros_like(got)
        for n in range(cov.shape[0]):
            w = cov[n].flatten()
            ref[:, n] = (f.flatten(2).double() * w).sum(-1).float() / float(w.sum())
        errs.append(float((got - ref).abs().max()))
    assert max(errs) <= 1e-5, errs
    return f"max |diff| per layer {['%.1e' % e for e in errs]}"


