def sha256(path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def real_batch(rows, n, load_dat=True, device=DEVICE):
    data = ImageRows(rows[:n], PROTOCOL, load_dat)
    batch = to_device(collate([data[i] for i in range(len(data))]), device)
    batch["y_z"] = TargetScaler.fit(rows).normalize(batch["y"])
    return batch


def nparams(m):
    return sum(p.numel() for p in m.parameters())


def p1a_module():
    """Import the P1a analysis script (read only) for its independent numpy coverage implementation."""
    spec = importlib.util.spec_from_file_location("p1a", P1A / "agmd_atlas_analysis.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def quiet(fn, *a, **k):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        out = fn(*a, **k)
    return out, buf.getvalue()


